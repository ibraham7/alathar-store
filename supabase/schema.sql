-- ============ Admin auth ============
create function private.require_admin(p_token uuid) returns void
language plpgsql security definer set search_path = public, private, extensions as $$
begin
  if p_token is null or not exists (select 1 from private.admin_sessions where token = p_token and expires_at > now()) then
    raise exception 'unauthorized' using errcode = '28000';
  end if;
end $$;

create function public.admin_login(p_password text) returns uuid
language plpgsql security definer set search_path = public, private, extensions as $$
declare v uuid;
begin
  delete from private.login_attempts where at < now() - interval '1 day';
  if (select count(*) from private.login_attempts where at > now() - interval '10 minutes') >= 10 then
    raise exception 'too_many_attempts';
  end if;
  if exists (select 1 from private.admin_auth where id = 1 and password_hash = crypt(p_password, password_hash)) then
    delete from private.admin_sessions where expires_at < now();
    insert into private.admin_sessions(expires_at) values (now() + interval '12 hours') returning token into v;
    return v;
  end if;
  insert into private.login_attempts default values;
  return null;
end $$;

create function public.admin_logout(p_token uuid) returns void
language sql security definer set search_path = public, private, extensions as $$
  delete from private.admin_sessions where token = p_token;
$$;

create function public.admin_token_valid(p_token uuid) returns boolean
language sql stable security definer set search_path = public, private, extensions as $$
  select exists (select 1 from private.admin_sessions where token = p_token and expires_at > now());
$$;

create function public.admin_change_password(p_token uuid, p_old text, p_new text) returns boolean
language plpgsql security definer set search_path = public, private, extensions as $$
begin
  perform private.require_admin(p_token);
  if length(coalesce(p_new,'')) < 6 then raise exception 'weak_password'; end if;
  update private.admin_auth set password_hash = crypt(p_new, gen_salt('bf'))
   where id = 1 and password_hash = crypt(p_old, password_hash);
  if not found then return false; end if;
  delete from private.admin_sessions where token <> p_token;
  return true;
end $$;

