create function public.admin_stats(p_token uuid) returns jsonb
language plpgsql security definer set search_path = public, private, extensions as $$
begin
  perform private.require_admin(p_token);
  return jsonb_build_object(
    'orders_count', (select count(*) from public.orders where status <> 'cancelled'),
    'new_count', (select count(*) from public.orders where status = 'new'),
    'revenue', (select coalesce(sum(total),0) from public.orders where status <> 'cancelled'),
    'revenue_today', (select coalesce(sum(total),0) from public.orders where status <> 'cancelled' and created_at >= date_trunc('day', now())),
    'revenue_month', (select coalesce(sum(total),0) from public.orders where status <> 'cancelled' and created_at >= date_trunc('month', now())),
    'items_sold', (select coalesce(sum(i.qty),0) from public.order_items i join public.orders o on o.id = i.order_id where o.status <> 'cancelled'),
    'products_count', (select count(*) from public.products),
    'low_stock', (select coalesce(jsonb_agg(jsonb_build_object('name', name, 'stock', stock) order by stock), '[]'::jsonb)
                    from public.products where is_active and stock <= 3),
    'top_products', (select coalesce(jsonb_agg(t order by t.qty desc), '[]'::jsonb) from (
                       select i.product_name as name, sum(i.qty)::int as qty, sum(i.qty * i.unit_price) as revenue
                       from public.order_items i join public.orders o on o.id = i.order_id
                       where o.status <> 'cancelled' group by 1 order by 2 desc limit 5) t),
    'daily', (select jsonb_agg(jsonb_build_object('day', d::date, 'total', coalesce(s.total,0), 'orders', coalesce(s.n,0)) order by d)
                from generate_series(date_trunc('day', now()) - interval '13 days', date_trunc('day', now()), interval '1 day') d
                left join (select date_trunc('day', created_at) dd, sum(total) total, count(*) n
                             from public.orders where status <> 'cancelled' group by 1) s on s.dd = d)
  );
end $$;

-- ============ Storefront: place an order ============
-- الأسعار والمخزون تُحسب هنا في القاعدة، لا في المتصفح.
create function public.place_order(p_customer jsonb, p_items jsonb) returns jsonb
language plpgsql security definer set search_path = public, private, extensions as $$
declare
  v_order public.orders;
  v_item jsonb;
  v_prod public.products;
  v_qty int;
  v_size text;
  v_sub numeric := 0;
  v_ship numeric;
begin
  if length(trim(coalesce(p_customer->>'name',''))) < 2 then raise exception 'name_required'; end if;
  if length(regexp_replace(coalesce(p_customer->>'phone',''), '\D', '', 'g')) < 7 then raise exception 'phone_required'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 40 then raise exception 'empty_cart'; end if;

  insert into public.orders(customer_name, phone, city, address, notes)
  values (left(trim(p_customer->>'name'),120), left(trim(p_customer->>'phone'),40), left(coalesce(p_customer->>'city',''),80),
          left(coalesce(p_customer->>'address',''),300), left(coalesce(p_customer->>'notes',''),500))
  returning * into v_order;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::int;
    v_size := left(coalesce(v_item->>'size',''), 20);
    if v_qty is null or v_qty not between 1 and 20 then raise exception 'bad_qty'; end if;
    select * into v_prod from public.products where id = (v_item->>'product_id')::uuid and is_active for update;
    if not found then raise exception 'product_unavailable'; end if;
    if v_prod.stock < v_qty then raise exception 'out_of_stock:%', v_prod.name; end if;
    update public.products set stock = stock - v_qty where id = v_prod.id;
    insert into public.order_items(order_id, product_id, product_name, size, qty, unit_price)
    values (v_order.id, v_prod.id, v_prod.name, v_size, v_qty, v_prod.price);
    v_sub := v_sub + v_prod.price * v_qty;
  end loop;

  select shipping_fee into v_ship from public.settings where id = 1;
  v_ship := coalesce(v_ship, 0);
  update public.orders set subtotal = v_sub, shipping_fee = v_ship, total = v_sub + v_ship where id = v_order.id;
  return jsonb_build_object('order_no', v_order.order_no, 'total', v_sub + v_ship);
end $$;

