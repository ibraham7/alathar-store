-- ============ Admin: orders & stats ============
create function public.admin_orders(p_token uuid) returns jsonb
language plpgsql security definer set search_path = public, private, extensions as $$
begin
  perform private.require_admin(p_token);
  return (
    select coalesce(jsonb_agg(to_jsonb(o) order by o.created_at desc), '[]'::jsonb)
    from (
      select o.*, (select coalesce(jsonb_agg(to_jsonb(i)), '[]'::jsonb) from public.order_items i where i.order_id = o.id) as items
      from public.orders o order by o.created_at desc limit 500
    ) o
  );
end $$;

create function public.admin_set_order_status(p_token uuid, p_id uuid, p_status text) returns void
language plpgsql security definer set search_path = public, private, extensions as $$
declare v_old text;
begin
  perform private.require_admin(p_token);
  select status into v_old from public.orders where id = p_id for update;
  if v_old is null then raise exception 'not_found'; end if;
  if v_old = p_status then return; end if;
  if p_status = 'cancelled' then      -- give stock back
    update public.products pr set stock = pr.stock + i.qty
      from (select product_id, sum(qty)::int qty from public.order_items where order_id = p_id group by 1) i
     where pr.id = i.product_id;
  elsif v_old = 'cancelled' then      -- take it again
    update public.products pr set stock = greatest(pr.stock - i.qty, 0)
      from (select product_id, sum(qty)::int qty from public.order_items where order_id = p_id group by 1) i
     where pr.id = i.product_id;
  end if;
  update public.orders set status = p_status where id = p_id;
end $$;

