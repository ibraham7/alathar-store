create function public.admin_save_product(p_token uuid, p jsonb) returns uuid
language plpgsql security definer set search_path = public, private, extensions as $$
declare v_id uuid := nullif(p->>'id','')::uuid;
        v_sizes text[] := array(select trim(x) from jsonb_array_elements_text(coalesce(p->'sizes','[]'::jsonb)) x where trim(x) <> '');
begin
  perform private.require_admin(p_token);
  if coalesce(trim(p->>'name'),'') = '' then raise exception 'name_required'; end if;
  if v_id is null then
    insert into public.products(name, description, price, old_price, category_id, sizes, color, image_url, stock, is_active, is_featured)
    values (trim(p->>'name'), coalesce(p->>'description',''), (p->>'price')::numeric, nullif(p->>'old_price','')::numeric,
            nullif(p->>'category_id','')::uuid, v_sizes, coalesce(nullif(p->>'color',''),'#B08968'), nullif(p->>'image_url',''),
            coalesce((p->>'stock')::int,0), coalesce((p->>'is_active')::boolean,true), coalesce((p->>'is_featured')::boolean,false))
    returning id into v_id;
  else
    update public.products set
      name = trim(p->>'name'), description = coalesce(p->>'description',''), price = (p->>'price')::numeric,
      old_price = nullif(p->>'old_price','')::numeric, category_id = nullif(p->>'category_id','')::uuid, sizes = v_sizes,
      color = coalesce(nullif(p->>'color',''),'#B08968'), image_url = nullif(p->>'image_url',''),
      stock = coalesce((p->>'stock')::int,0), is_active = coalesce((p->>'is_active')::boolean,true),
      is_featured = coalesce((p->>'is_featured')::boolean,false)
    where id = v_id;
  end if;
  return v_id;
end $$;

